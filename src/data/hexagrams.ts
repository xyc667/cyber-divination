export function getHexagramById(id: string): Hexagram | undefined {
  return hexagrams.find(h => h.id === id);
}

export function getHexagramByNumber(number: number): Hexagram | undefined {
  return hexagrams.find(h => h.number === number);
}

export function getHexagramByName(name: string): Hexagram | undefined {
  return hexagrams.find(h => h.name === name);
}

export function searchHexagrams(query: string): Hexagram[] {
  const lowerQuery = query.toLowerCase();
  return hexagrams.filter(h => 
    h.name.includes(query) ||
    h.pinyin.includes(lowerQuery) ||
    h.guaci.includes(query) ||
    h.xiang.includes(query)
  );
}
